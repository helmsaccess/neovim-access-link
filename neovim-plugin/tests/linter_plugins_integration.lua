local diagnostic_events = {}
vim.api.nvim_create_autocmd("DiagnosticChanged", {
  callback = function(args)
    diagnostic_events[args.buf] = (diagnostic_events[args.buf] or 0) + 1
  end,
})

local access_diagnostics = require("nvim_nvda.diagnostics")
local severity_names = {
  [vim.diagnostic.severity.ERROR] = "error",
  [vim.diagnostic.severity.WARN] = "warning",
  [vim.diagnostic.severity.INFO] = "information",
  [vim.diagnostic.severity.HINT] = "hint",
}
local function matches(case, diagnostic)
  local native_source
  if not case.source_missing then
    native_source = case.source
  end
  return diagnostic.source == native_source and diagnostic.code == case.code
    and (not case.message_pattern or diagnostic.message:find(case.message_pattern))
end

for _, case in ipairs(cases) do
  local case_root = fixture_root .. "/" .. case.directory
  vim.cmd("lcd " .. vim.fn.fnameescape(case_root))
  vim.cmd("edit " .. vim.fn.fnameescape(case_root .. "/" .. case.file))
  local buffer = vim.api.nvim_get_current_buf()
  vim.bo[buffer].filetype = case.filetype
  vim.diagnostic.reset(nil, buffer)
  diagnostic_events[buffer] = 0

  if provider == "ale" then
    local linted_before = vim.fn.getbufvar(buffer, "ale_linted", 0)
    vim.cmd("ALELint")
    local completed = vim.wait(15000, function()
      return vim.fn.getbufvar(buffer, "ale_linted", 0) > linted_before
    end, 20)
    if not completed then
      print(case.name .. " incomplete ALE history: "
        .. vim.inspect(vim.fn.getbufvar(buffer, "ale_history", {})))
    end
    truth(completed, case.name .. " ALE run completes")
  else
    require("lint").try_lint(case.name, { cwd = case_root })
    local published = vim.wait(15000, function()
      for _, diagnostic in ipairs(vim.diagnostic.get(buffer)) do
        if matches(case, diagnostic) then return true end
      end
      return false
    end, 20)
    if not published then
      print(case.name .. " diagnostics: " .. vim.inspect(vim.diagnostic.get(buffer)))
    end
    truth(published, case.name .. " nvim-lint run publishes its target diagnostic")
  end

  if provider == "ale" then
    vim.wait(2000, function()
      for _, diagnostic in ipairs(vim.diagnostic.get(buffer)) do
        if matches(case, diagnostic) then return true end
      end
      return false
    end, 20)
  end

  local target
  for _, diagnostic in ipairs(vim.diagnostic.get(buffer)) do
    if matches(case, diagnostic) then
      target = diagnostic
      break
    end
  end
  if not target then
    print(case.name .. " unmatched diagnostics: "
      .. vim.inspect(vim.diagnostic.get(buffer)))
  end
  truth(type(target) == "table",
    case.name .. " publishes its provider identity through vim.diagnostic")
  truth(type(target.message) == "string" and target.message ~= "",
    case.name .. " publishes a nonempty message")
  truth(type(severity_names[target.severity]) == "string",
    case.name .. " publishes a recognized severity")
  truth(type(target.lnum) == "number" and type(target.col) == "number"
    and type(target.end_lnum) == "number" and type(target.end_col) == "number",
    case.name .. " publishes a complete range")
  truth((diagnostic_events[buffer] or 0) > 0,
    case.name .. " produces a DiagnosticChanged event")

  vim.api.nvim_win_set_cursor(0, { target.lnum + 1, target.col })
  local snapshot, count = access_diagnostics.snapshot(buffer, target.lnum + 1, target.col)
  truth(count > 0 and type(snapshot) == "table",
    case.name .. " reaches the Access Link diagnostic snapshot")
  truth(snapshot.source == case.source and snapshot.code == case.code,
    case.name .. " preserves provider identity and diagnostic code")
  truth(snapshot.message == target.message and snapshot.severity == severity_names[target.severity],
    case.name .. " preserves message and severity")
  truth(snapshot.line == target.lnum + 1 and snapshot.byteColumn == target.col,
    case.name .. " preserves the native byte-range start")
  truth(snapshot.endLine == target.end_lnum + 1 and snapshot.endByteColumn == target.end_col,
    case.name .. " preserves the native byte-range end")
  truth(type(snapshot.index) == "number" and type(snapshot.count) == "number"
    and snapshot.index >= 1 and snapshot.index <= snapshot.count,
    case.name .. " publishes a valid provider-neutral position")
end

print(string.format("real %s linter integration: %d assertions passed", provider, assertions))
vim.cmd("qa!")
