    name = "clangtidy",
    directory = "c",
    file = "broken.c",
    filetype = "c",
    lines = { "int main(void) { return missing; }" },
    source = provider == "nvim-lint" and "clang-tidy" or "clangtidy",
    code = provider == "nvim-lint" and "clang-diagnostic-error" or nil,
    message_pattern = provider == "ale" and "%[clang%-diagnostic%-error%]" or nil,
  },
  {
    name = "ruff",
    directory = "python",
    file = "broken.py",
    filetype = "python",
    lines = { "import os", "print(missing)" },
    source = "ruff",
    code = "F821",
  },
  {
    name = "shellcheck",
    directory = "bash",
    file = "broken.sh",
    filetype = "sh",
    lines = { "#!/bin/bash", 'value="hello world"', "echo $value" },
    source = "shellcheck",
    code = provider == "nvim-lint" and 2086 or "SC2086",
  },
  {
    name = "staticcheck",
    directory = "go",
    file = "broken.go",
    filetype = "go",
    lines = {
      "package main",
