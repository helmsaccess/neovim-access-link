local root = vim.fn.getcwd()
local nvim_lint_root = vim.env.NVIM_NVDA_NVIM_LINT_ROOT
local ale_root = vim.env.NVIM_NVDA_ALE_ROOT
local fixture_root = vim.env.NVIM_NVDA_LINTER_TEST_ROOT
local provider = vim.env.NVIM_NVDA_LINTER_PROVIDER

assert(type(nvim_lint_root) == "string" and vim.fn.isdirectory(nvim_lint_root) == 1,
  "NVIM_NVDA_NVIM_LINT_ROOT must name an nvim-lint checkout")
assert(type(ale_root) == "string" and vim.fn.isdirectory(ale_root) == 1,
  "NVIM_NVDA_ALE_ROOT must name an ALE checkout")
assert(type(fixture_root) == "string" and vim.fn.isdirectory(fixture_root) == 1,
  "NVIM_NVDA_LINTER_TEST_ROOT must name an isolated directory")
assert(provider == "nvim-lint" or provider == "ale",
  "NVIM_NVDA_LINTER_PROVIDER must be nvim-lint or ale")

nvim_lint_root = vim.fn.fnamemodify(nvim_lint_root, ":p")
ale_root = vim.fn.fnamemodify(ale_root, ":p")
local provider_root = provider == "nvim-lint" and nvim_lint_root or ale_root
for _, value in ipairs({ root .. "/neovim-plugin", provider_root }) do
  vim.opt.runtimepath:prepend(value)
  package.path = value .. "/lua/?.lua;" .. value .. "/lua/?/init.lua;" .. package.path
end

local assertions = 0
local function truth(value, label)
  assertions = assertions + 1
  assert(value, label)
end

local cases = {
